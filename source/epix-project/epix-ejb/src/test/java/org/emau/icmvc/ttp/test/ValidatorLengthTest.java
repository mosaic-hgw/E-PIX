import org.emau.icmvc.ttp.deduplication.impl.validation.LengthValidator;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

class ValidatorLengthTest
{
	@Test
	void testAllowedLength()
	{
		LengthValidator val = new LengthValidator(5);

		assertTrue(val.validate("12345"));
	}

	@Test
	void testNull()
	{
		LengthValidator val1 = new LengthValidator(5);
		assertFalse(val1.validate(null));

		LengthValidator val2 = new LengthValidator(0);
		assertTrue(val2.validate(null));
	}

	@Test
	void testNotAllowedLength()
	{
		LengthValidator val = new LengthValidator(5);

		assertFalse(val.validate("1234567890"));
	}
}
